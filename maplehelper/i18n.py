class I18n:
    def __init__(self, lang: str = "he"):
        self.lang = lang if lang in ("he", "en") else "he"

    @property
    def rtl(self) -> bool:
        return self.lang == "he"

    def __call__(self, _key: str, **kw) -> str:
        s = STRINGS.get(_key, {}).get(self.lang) or STRINGS.get(_key, {}).get("en") or _key
        return s.format(**kw) if kw else s
